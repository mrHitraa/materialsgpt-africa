import { createFileRoute, useRouter } from "@tanstack/react-router";
import { useSuspenseQuery } from "@tanstack/react-query";
import { LineChart } from "lucide-react";
import { EmptyState, ErrorState, LoadingState, PageHeader } from "@/components/common/states";
import { DemoBadge } from "@/components/common/DemoBadge";
import { StageHandoff } from "@/components/pipeline/StageHandoff";
import { PredictionImportForm } from "@/components/predictions/PredictionImportForm";
import { DatabaseRateEstimator } from "@/components/predictions/DatabaseRateEstimator";
import { literatureQuery, predictionRecordsQuery } from "@/lib/data/queries";
import { conditionContext } from "@/lib/data/pending-storage";

export const Route = createFileRoute("/predictions")({
  head: () => ({
    meta: [
      { title: "Predictions · MaterialsGPT Africa" },
      {
        name: "description",
        content: "Imported service-life predictions from external scientific models.",
      },
      { property: "og:title", content: "Predictions · MaterialsGPT Africa" },
      {
        property: "og:description",
        content: "Imported service-life predictions from external scientific models.",
      },
    ],
  }),
  loader: ({ context }) =>
    Promise.all([
      context.queryClient.ensureQueryData(predictionRecordsQuery),
      context.queryClient.ensureQueryData(literatureQuery),
    ]),
  pendingComponent: () => <LoadingState label="Loading model outputs…" />,
  errorComponent: ({ error }) => (
    <RetryError message={error instanceof Error ? error.message : String(error)} />
  ),
  component: Page,
});

function RetryError({ message }: { message: string }) {
  const router = useRouter();
  return <ErrorState message={message} onRetry={() => router.invalidate()} />;
}

function Page() {
  const { data: predictions } = useSuspenseQuery(predictionRecordsQuery);
  const { data: literature } = useSuspenseQuery(literatureQuery);
  const rateEvidence = literature.flatMap((source) =>
    source.corrosion_observations.map((observation) => ({
      ...observation,
      ...conditionContext(observation as typeof observation & Parameters<typeof conditionContext>[0]),
      source: {
        title: source.title,
        doi: source.doi,
        source_url: source.source_url,
        is_demo: source.is_demo,
      },
    })),
  );
  return (
    <>
      <PageHeader
        title="Predictions"
        description="Database-derived exact-condition corrosion-rate estimates and traceable outputs imported from external models. No service-life predictions are generated."
      />
      <StageHandoff stageId="predict" />
      <DatabaseRateEstimator records={rateEvidence} />
      <div className="grid gap-6 xl:grid-cols-[1fr_380px]">
        <div className="space-y-4">
          {predictions.length === 0 ? (
            <EmptyState
              icon={LineChart}
              title="No model outputs imported"
              description="No service-life or degradation predictions are stored. Import a result from an approved model; no prediction values are generated by this app."
            />
          ) : (
            predictions.map((prediction) => (
              <article key={prediction.id} className="rounded-lg border bg-card p-5">
                <div className="flex flex-wrap items-start justify-between gap-3">
                  <div>
                    <h2 className="font-semibold">
                      {prediction.material_name} · {prediction.metric_name}
                    </h2>
                    <p className="mt-1 text-xs text-muted-foreground">
                      {prediction.model_name} v{prediction.model_version} ·{" "}
                      {prediction.temperature_c} °C · {prediction.salt_composition}
                    </p>
                  </div>
                  <span className="rounded bg-warning px-2 py-1 font-mono text-[10px] text-warning-foreground">
                    Imported · not independently validated
                  </span>
                </div>
                <p className="mt-4 font-mono text-2xl font-semibold">
                  {prediction.predicted_value} {prediction.metric_unit}
                  {prediction.is_demo && <DemoBadge />}
                </p>
                <dl className="mt-4 grid gap-3 text-xs sm:grid-cols-2">
                  <div>
                    <dt className="font-medium">Predicted endpoint / failure criterion</dt>
                    <dd className="mt-1 text-muted-foreground">{prediction.failure_criterion}</dd>
                  </div>
                  <div>
                    <dt className="font-medium">Model inputs and operating conditions</dt>
                    <dd className="mt-1 whitespace-pre-wrap text-muted-foreground">
                      {prediction.model_input_summary}
                    </dd>
                  </div>
                  <div>
                    <dt className="font-medium">Assumptions</dt>
                    <dd className="mt-1 whitespace-pre-wrap text-muted-foreground">
                      {prediction.assumptions}
                    </dd>
                  </div>
                  {prediction.uncertainty && (
                    <div>
                      <dt className="font-medium">Reported uncertainty</dt>
                      <dd className="mt-1 whitespace-pre-wrap text-muted-foreground">
                        {prediction.uncertainty}
                      </dd>
                    </div>
                  )}
                </dl>
                <a
                  href={prediction.model_reference_url}
                  target="_blank"
                  rel="noreferrer"
                  className="mt-4 inline-block text-xs text-primary hover:underline"
                >
                  Model source
                </a>
                <p className="mt-2 text-[10px] text-muted-foreground">
                  Imported {prediction.created_at.slice(0, 10)}
                </p>
              </article>
            ))
          )}
        </div>
        <PredictionImportForm />
      </div>
    </>
  );
}
